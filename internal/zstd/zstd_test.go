func TestSamples(t *testing.T) {
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			r := NewReader(strings.NewReader(test.compressed))
			got, err := io.ReadAll(r)
			if err != nil {
				t.Fatal(err)
			}
			gotstr := string(got)
			if gotstr != test.uncompressed {
				t.Errorf("got %q want %q", gotstr, test.uncompressed)
			}
		})
	}
}

func TestReset(t *testing.T) {
	input := strings.NewReader("")
	r := NewReader(input)
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			input.Reset(test.compressed)
			r.Reset(input)
			got, err := io.ReadAll(r)
			if err != nil {
				t.Fatal(err)
			}
			gotstr := string(got)
			if gotstr != test.uncompressed {
				t.Errorf("got %q want %q", gotstr, test.uncompressed)
			}
		})
	}
}

func TestCorruptInputs(t *testing.T) {
	badInputs := []struct {
		name string
		data string
	}{
		{name: "bad magic", data: "not-a-zstd-stream"},
		{name: "short header", data: "\x28\xb5\x2f\xfd"},
		{name: "bad checksum", data: "\x28\xb5\x2f\xfd\x24\x0d\x69\x00\x00\x68\x65\x6c\x6c\x6f\x2c\x20\x77\x6f\x72\x6c\x64\x0a\x00\x00\x00\x00"},
	}
	for _, tc := range badInputs {
		t.Run(tc.name, func(t *testing.T) {
			r := NewReader(strings.NewReader(tc.data))
			if _, err := io.ReadAll(r); err == nil {
				t.Fatalf("expected error for %s, got nil", tc.name)
			}
		})
	}
}
